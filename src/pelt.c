/*
 * Userspace port of Linux per-entity load tracking.
 *
 * Ported from kernel/sched/pelt.c, kernel/sched/pelt.h and
 * kernel/sched/sched-pelt.h (torvalds/linux master, checked 2026-10-18).
 * The arithmetic, integer widths and constants follow the kernel so that the
 * same sequence of (now, load, runnable, running) inputs gives bit-identical
 * sums and averages. Kernel-only details are dropped: CFS bandwidth
 * throttling, rt/dl/irq signals, util_est flags, READ/WRITE_ONCE.
 *
 * The PELT multiplier (x2/x4) is not in mainline pelt.c; it follows the
 * out-of-tree "sched/pelt: Introduce PELT multiplier" series (v2, Dec 2023),
 * which adds a task clock advanced with deltas << shift.
 */
#include "pelt.h"

/* Generated by Documentation/scheduler/sched-pelt: 0xffffffff * y^i, y^32 = 1/2. */
const uint32_t pelt_runnable_avg_yN_inv[PELT_LOAD_AVG_PERIOD] = {
    0xffffffff, 0xfa83b2da, 0xf5257d14, 0xefe4b99a, 0xeac0c6e6, 0xe5b906e6,
    0xe0ccdeeb, 0xdbfbb796, 0xd744fcc9, 0xd2a81d91, 0xce248c14, 0xc9b9bd85,
    0xc5672a10, 0xc12c4cc9, 0xbd08a39e, 0xb8fbaf46, 0xb504f333, 0xb123f581,
    0xad583ee9, 0xa9a15ab4, 0xa5fed6a9, 0xa2704302, 0x9ef5325f, 0x9b8d39b9,
    0x9837f050, 0x94f4efa8, 0x91c3d373, 0x8ea4398a, 0x8b95c1e3, 0x88980e80,
    0x85aac367, 0x82cd8698,
};

static inline uint64_t mul_u64_u32_shr(uint64_t a, uint32_t mul, unsigned int shift) {
    return (uint64_t)(((unsigned __int128)a * mul) >> shift);
}

static inline uint64_t cap_scale(uint64_t v, unsigned long s) { return (v * s) >> SCHED_CAPACITY_SHIFT; }

/* val * y^n, constant time: whole half-lives as shifts, the rest from the table. */
uint64_t pelt_decay_load(uint64_t val, uint64_t n) {
    unsigned int local_n;

    if (n > PELT_LOAD_AVG_PERIOD * 63) return 0;
    local_n = (unsigned int)n;
    if (local_n >= PELT_LOAD_AVG_PERIOD) {
        val >>= local_n / PELT_LOAD_AVG_PERIOD;
        local_n %= PELT_LOAD_AVG_PERIOD;
    }
    return mul_u64_u32_shr(val, pelt_runnable_avg_yN_inv[local_n], 32);
}

/* Contribution of d1 (rest of the old period), the full periods in between, and d3 (start of the current one). */
uint32_t pelt_accumulate_segments(uint64_t periods, uint32_t d1, uint32_t d3) {
    uint32_t c1, c2, c3 = d3;

    c1 = (uint32_t)pelt_decay_load((uint64_t)d1, periods);
    c2 = (uint32_t)(PELT_LOAD_AVG_MAX - pelt_decay_load(PELT_LOAD_AVG_MAX, periods) - 1024);
    return c1 + c2 + c3;
}

uint32_t pelt_accumulate_sum(uint64_t delta, PeltAvg *sa, unsigned long load, unsigned long runnable, int running) {
    uint32_t contrib = (uint32_t)delta; /* periods == 0 -> delta < 1024 */
    uint64_t periods;

    delta += sa->period_contrib;
    periods = delta / 1024;

    if (periods) {
        sa->load_sum = pelt_decay_load(sa->load_sum, periods);
        sa->runnable_sum = pelt_decay_load(sa->runnable_sum, periods);
        sa->util_sum = (uint32_t)pelt_decay_load((uint64_t)sa->util_sum, periods);

        delta %= 1024;
        if (load) contrib = pelt_accumulate_segments(periods, 1024 - sa->period_contrib, (uint32_t)delta);
    }
    sa->period_contrib = (uint32_t)delta;

    if (load) sa->load_sum += load * contrib;
    if (runnable) sa->runnable_sum += runnable * contrib << SCHED_CAPACITY_SHIFT;
    if (running) sa->util_sum += contrib << SCHED_CAPACITY_SHIFT;

    return (uint32_t)periods;
}

/* Time is in ns; >> 10 makes 1024 ns "us", so a period is 1024 * 1024 ns. */
int pelt_update_load_sum(uint64_t now, PeltAvg *sa, unsigned long load, unsigned long runnable, int running) {
    uint64_t delta = now - sa->last_update_time;

    if ((int64_t)delta < 0) {
        sa->last_update_time = now;
        return 0;
    }
    delta >>= 10;
    if (!delta) return 0;
    sa->last_update_time += delta << 10;

    if (!load) runnable = running = 0;
    if (!pelt_accumulate_sum(delta, sa, load, runnable, running)) return 0;
    return 1;
}

void pelt_update_load_avg(PeltAvg *sa, unsigned long load) {
    uint32_t divider = PELT_MIN_DIVIDER + sa->period_contrib;

    sa->load_avg = (unsigned long)(load * sa->load_sum / divider);
    sa->runnable_avg = (unsigned long)(sa->runnable_sum / divider);
    sa->util_avg = sa->util_sum / divider;
}

int pelt_update(uint64_t now, PeltAvg *sa, unsigned long sum_load, unsigned long runnable, int running,
                unsigned long avg_load) {
    if (!pelt_update_load_sum(now, sa, sum_load, runnable, running)) return 0;
    pelt_update_load_avg(sa, avg_load);
    return 1;
}

void pelt_clock_init(PeltClock *c, unsigned int shift) {
    c->clock_task = c->clock_task_mult = c->clock_pelt = c->lost_idle_time = 0;
    c->shift = shift;
}

void pelt_clock_advance(PeltClock *c, uint64_t delta_ns, bool busy, unsigned long cpu_scale,
                        unsigned long freq_scale, uint32_t cpu_util_sum) {
    if (!busy) {
        /* update_idle_rq_clock_pelt(): if the CPU was saturated, the time it
         * lost to running slowly is not given back as idle time. */
        uint32_t divider = ((PELT_LOAD_AVG_MAX - 1024) << SCHED_CAPACITY_SHIFT) - PELT_LOAD_AVG_MAX;
        if (cpu_util_sum >= divider) c->lost_idle_time += c->clock_task_mult - c->clock_pelt;
    }
    uint64_t delta = delta_ns << c->shift;
    c->clock_task += delta_ns;
    c->clock_task_mult += delta;
    if (busy) {
        delta = cap_scale(delta, cpu_scale);
        delta = cap_scale(delta, freq_scale);
        c->clock_pelt += delta;
    } else {
        c->clock_pelt = c->clock_task_mult; /* _update_idle_rq_clock_pelt() */
    }
}

uint64_t pelt_clock_now(const PeltClock *c) { return c->clock_pelt - c->lost_idle_time; }
